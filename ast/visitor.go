package ast

type AstVisitor interface {
	visitAst(Ast)
	visitFunctionDef(FunctionDef)
	visitPrintStatement(PrintStmt)
	visitAssignStatement(AssignStmt)
	visitVoidFunctionCallStatement(VoidFunctionCall)
	visitAssert(AssertStmt)
	visitReturn(ReturnStmt)
	visitReturnWithExpr(ReturnWithExprStmt)
	visitIfStatement(IfStmt)
	visitWhileStatement(WhileStmt)
	visitBinaryExpression(BinaryExpr)
	visitUnaryExpression(UnaryExpr)
	visitInt(Int)
	visitFloat(Float)
	visitBool(Bool)
	visitVar(Var)
	visitNone(None)
	visitFunctionCall(FunctionCall)
	visitAddressOfFunction(AddressOfFunction)
	visitTernaryExpression(TernaryExpr)
	visitNewListExpression(NewListExpr)
	visitNewObjectExpression(NewObjectExpr)
	visitLenExpression(LenExpr)
	visitSubscriptGetExpression(SubscriptGet)
	visitObjectFieldGetExpression(ObjectFieldGet)
	visitAssignVarExpression(AssignVar)
	visitObjectFieldSetExpression(ObjectFieldSet)
	visitSubscriptSetExpression(SubscriptSet)
}
